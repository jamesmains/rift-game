#!/usr/bin/env python3
"""Compiles assets/data/tilekinds.txt into src/game/tilekinds_builtin.h (the game's built-in tile kinds).

Run from the project's src folder after changing tilekinds.txt by hand or in the Editor's Tiles tab:
    python tools/mktilekinds.py
build.ps1 runs it before every build, so the built-ins always match the shipped file.
Every key is passed through as written (1.8.0: daybg= / daytint=, the hand-picked day colours, too); the game
works the day colours out at load (computeTileKindDayColors in world.cpp), so nothing is baked in here.
"""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
src = os.path.join(root, 'assets', 'data', 'tilekinds.txt')
dst = os.path.join(root, 'src', 'game', 'tilekinds_builtin.h')

lines = [l.rstrip() for l in open(src, encoding='utf-8')]
lines = [l for l in lines if l and not l.startswith('#')]
chunks, cur = [], ''
for l in lines:
    if l == '[kind]' and len(cur) > 12000:   # MSVC limits one string literal to ~16 KB
        chunks.append(cur); cur = ''
    cur += l + '\n'
if cur:
    chunks.append(cur)

out = ['// Generated by tools/mktilekinds.py from assets/data/tilekinds.txt - do not edit by hand.',
       '#pragma once', '', 'static const char* const kBuiltinTileKinds[] = {']
for c in chunks:
    out.append('R"TK(' + c + ')TK",')
out += ['nullptr', '};', '']
text = '\n'.join(out)
old = open(dst, encoding='utf-8').read() if os.path.exists(dst) else ''
if old != text:
    open(dst, 'w', encoding='utf-8', newline='\n').write(text)
    print('wrote', os.path.relpath(dst, root), '(%d kinds)' % sum(1 for l in lines if l == '[kind]'))
