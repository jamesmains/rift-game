#!/usr/bin/env python3
"""Compiles assets/data/sounds.txt into src/core/sounds_builtin.h (Audio::defaultDefsText, written when a copy has no
sounds.txt). 1.3.4: before, the defaults were a hand-kept copy of sounds.txt in audio.cpp.

Run from the project's src folder (build.ps1 runs it before every build):
    python tools/mksoundsdefault.py
"""
import os

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
src = os.path.join(root, 'assets', 'data', 'sounds.txt')
dst = os.path.join(root, 'src', 'core', 'sounds_builtin.h')

text = open(src, encoding='utf-8').read().replace('\r\n', '\n')
chunks, cur = [], ''
for block in text.split('\n\n'):
    if len(cur) > 12000:   # MSVC limits one string literal to ~16 KB
        chunks.append(cur); cur = ''
    cur += block + '\n\n'
if cur:
    chunks.append(cur.rstrip('\n') + '\n')

out = ['// Generated by tools/mksoundsdefault.py from assets/data/sounds.txt - do not edit by hand.',
       '#pragma once', '', 'static const char* const kBuiltinSounds[] = {']
for c in chunks:
    out.append('R"SND(' + c + ')SND",')
out += ['nullptr', '};', '']
new = '\n'.join(out)
old = open(dst, encoding='utf-8').read() if os.path.exists(dst) else ''
if new != old:
    with open(dst, 'w', encoding='utf-8', newline='\n') as f:
        f.write(new)
    print('wrote', dst)
